--[[
	Тулы в руках игрока: как они опознаются, какой из них важнее и что рисует
	кнопка использования.

	Тип тула — строка в аттрибуте ToolTypeAttribute на самом Tool. Ставит её
	тот, кто тул создаёт (сервер), а клиент по ней решает, что в руках
	и что делать по кнопке.

	В шаблоне таблицы пустые НАМЕРЕННО: своих тулов у каркаса нет. Игра
	заполняет их своими типами, а действия регистрирует в рантайме через
	ToolsController:RegisterAction.
]]

local ToolsConfig = {}

ToolsConfig.ToolTypeAttribute = "ToolType"

--[[
	Что важнее держать в руках, если тулов несколько. Больше число — важнее.
	Незнакомый тип получает ноль и в руки не берётся.

	Пример:
		ToolsConfig.Priority = {Fish = 2; FishingRod = 1}
]]
ToolsConfig.Priority = {}

--[[
	Что рисует экранная кнопка использования для каждого типа тула.
	Незнакомый тип обязан прятать кнопку целиком.

	Самой кнопки в каркасе НЕТ: её вид и место зависят от игры. Эта таблица —
	готовый контракт для неё, чтобы подпись и иконка не расползлись по коду.

	Пустой ImageId — штатное состояние: кнопка тогда показывает Label.

	Пример:
		ToolsConfig.Actions = {
			FishingRod = {Label = "FISH"; ImageId = ""};
		}
]]
ToolsConfig.Actions = {}

return ToolsConfig
